#!/usr/bin/env python3
"""Serve the app over HTTPS on the home network, so phones and tablets can use it.

Browsers accept Keycloak's login cookies over plain HTTP only on localhost: any other device
needs HTTPS with a certificate it trusts. This script, idempotent:

1. finds the machine's LAN name (`<name>.local`) and IP address;
2. creates a certificate authority for this project (in `secrets/tls/ca`, not in the system
   keychain) and, with it, a certificate for those addresses (`mkcert` must be installed);
3. writes `secrets/tls/tls.yml`, from which Traefik serves that certificate on its HTTPS entry
   point (published as 8443), picking it up without a restart;
4. adds the HTTPS addresses to `.env` (allowed hosts, CSRF origins, Keycloak redirect URIs);
5. leaves `secrets/tls/mymenu-local-ca.crt` to install, once, on each phone or tablet.

Re-run it when the machine's IP changes: the certificate is reissued for the new address, but
the certificate authority stays the same, so devices that trust it keep trusting it.

    python3 scripts/setup_lan_https.py [--host extra.name] [--port 8443]
"""

from __future__ import annotations

import argparse
import os
import platform
import re
import shutil
import socket
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TLS = ROOT / "secrets" / "tls"
CA_DIR = TLS / "ca"
ENV_FILE = ROOT / ".env"

# Traefik dynamic configuration; secrets/tls is mounted at /etc/traefik/dynamic.
TRAEFIK_TLS = """\
# Generated by scripts/setup_lan_https.py. Certificate issued for: {hosts}
tls:
  stores:
    default:
      defaultCertificate:
        certFile: /etc/traefik/dynamic/cert.pem
        keyFile: /etc/traefik/dynamic/key.pem
"""


def lan_ip() -> str:
    """The address other devices on the network reach this machine at.

    Connecting a UDP socket sends nothing; it only makes the OS pick the outgoing interface.
    """
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as probe:
        probe.connect(("192.0.2.1", 9))
        return probe.getsockname()[0]


def lan_name() -> str | None:
    """`<name>.local`, which phones resolve through mDNS/Bonjour."""
    if platform.system() == "Darwin":
        name = subprocess.run(
            ["scutil", "--get", "LocalHostName"], capture_output=True, text=True
        ).stdout.strip()
    else:
        name = socket.gethostname().split(".")[0]
    return f"{name}.local" if name else None


def update_env_list(text: str, key: str, values: list[str]) -> tuple[str, list[str]]:
    """Add missing values to a comma-separated KEY=a,b line. Returns (text, added)."""
    match = re.search(rf"^{key}=(.*)$", text, re.M)
    current = [v.strip() for v in (match.group(1) if match else "").split(",") if v.strip()]
    added = [v for v in values if v not in current]
    if not added:
        return text, []
    line = f"{key}={','.join(current + added)}"
    text = re.sub(rf"^{key}=.*$", line, text, flags=re.M) if match else text + f"\n{line}\n"
    return text, added


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--host", action="append", default=[], help="extra name or IP to cover")
    parser.add_argument("--port", type=int, default=int(os.getenv("LAN_HTTPS_PORT", "8443")))
    args = parser.parse_args()

    mkcert = shutil.which("mkcert")
    if not mkcert:
        print("mkcert is needed: brew install mkcert (macOS) or see github.com/FiloSottile/mkcert")
        return 1
    if not ENV_FILE.exists():
        print("No .env yet: run python3 scripts/init_env.py first.")
        return 1

    hosts = [h for h in [lan_name(), lan_ip(), *args.host] if h]
    TLS.mkdir(parents=True, exist_ok=True)
    CA_DIR.mkdir(exist_ok=True)

    # Reissue the certificate only when the set of addresses changed.
    hosts_file = TLS / "hosts.txt"
    covered = hosts_file.read_text().split() if hosts_file.exists() else []
    if sorted(covered) != sorted(hosts) or not (TLS / "cert.pem").exists():
        env = {**os.environ, "CAROOT": str(CA_DIR)}
        subprocess.run(
            [mkcert, "-cert-file", str(TLS / "cert.pem"), "-key-file", str(TLS / "key.pem"),
             *hosts],
            env=env, check=True, capture_output=True,
        )
        hosts_file.write_text("\n".join(hosts) + "\n")
        print(f"issued a certificate for {', '.join(hosts)}")
    else:
        print(f"certificate already covers {', '.join(hosts)}")
    (TLS / "key.pem").chmod(0o644)  # read by Traefik inside its container
    shutil.copyfile(CA_DIR / "rootCA.pem", TLS / "mymenu-local-ca.crt")
    (TLS / "tls.yml").write_text(TRAEFIK_TLS.format(hosts=", ".join(hosts)))
    # Left over from when nginx terminated TLS.
    (TLS / "https.conf").unlink(missing_ok=True)

    text = ENV_FILE.read_text()
    urls = [f"https://{h}:{args.port}" for h in hosts]
    changes = []
    for key, values in [
        ("DJANGO_ALLOWED_HOSTS", hosts),
        ("DJANGO_CSRF_TRUSTED_ORIGINS", urls),
        ("APP_PUBLIC_URLS", urls),
    ]:
        text, added = update_env_list(text, key, values)
        changes += [f"{key} += {a}" for a in added]
    if changes:
        ENV_FILE.write_text(text)
        print("updated .env:", *changes, sep="\n  ")

    print(f"""
Next:
  1. Apply it:  docker compose up -d backend keycloak-setup   (Traefik reloads the certificate itself)
  2. On each phone or tablet, once, trust the certificate authority:
     send secrets/tls/mymenu-local-ca.crt to it (AirDrop, email to yourself), open it, then
     - iPhone/iPad: Settings > General > VPN & Device Management > install the profile, then
       Settings > General > About > Certificate Trust Settings > enable "mkcert ...".
     - Android: Settings > Security > Encryption & credentials > Install a certificate >
       CA certificate.
  3. Open https://{hosts[0]}:{args.port} (or https://{hosts[1] if len(hosts) > 1 else hosts[0]}:{args.port}).

The certificate authority's private key is in secrets/tls/ca (gitignored): whoever has it can
issue certificates your devices will trust. Never share it; share only the .crt file.""")
    return 0


if __name__ == "__main__":
    sys.exit(main())
